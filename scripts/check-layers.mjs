#!/usr/bin/env node
/**
 * Static dependency guard for the source tree.
 *
 * This intentionally uses no dependency: it catches new layering violations
 * before the domain migration is complete. The allowlist is temporary and is
 * expected to shrink as Phase 1.4 and Phase 5 land.
 */
import { mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";

const ROOT = resolve(new URL("..", import.meta.url).pathname, "src");
const GRAPH_OUT = resolve(new URL("..", import.meta.url).pathname, "docs", "architecture-graph.md");

// Existing violations intentionally retained until their planned phase.
const ALLOWLIST = new Set([
]);

function sourceFiles(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) sourceFiles(path, out);
    else if (/\.(ts|tsx)$/.test(name)) out.push(path);
  }
  return out;
}

function importsFrom(text) {
  const imports = [];
  const fromRe = /\bfrom\s+["'](\.[^"']+)["']/g;
  const sideEffectRe = /\bimport\s*["'](\.[^"']+)["']/g;
  for (const match of text.matchAll(fromRe)) imports.push(match[1]);
  for (const match of text.matchAll(sideEffectRe)) imports.push(match[1]);
  return imports;
}

function normalizeImport(file, specifier) {
  const from = relative(ROOT, file).replaceAll("\\", "/");
  return `${from} -> ${specifier}`;
}

function resolveSource(file, specifier) {
  const base = resolve(file, "..", specifier.replace(/\.js$/, ""));
  for (const suffix of ["", ".ts", ".tsx", ".js"]) {
    const candidate = `${base}${suffix}`;
    try {
      if (statSync(candidate).isFile()) return candidate.replace(/\.js$/, ".ts");
    } catch {
      // Try the next source extension.
    }
  }
  return null;
}

function check() {
  const violations = [];
  const edges = [];
  for (const file of sourceFiles(ROOT)) {
    const from = relative(ROOT, file).replaceAll("\\", "/");
    for (const specifier of importsFrom(readFileSync(file, "utf8"))) {
      const to = resolveSource(file, specifier);
      if (!to) continue;
      const target = relative(ROOT, to).replaceAll("\\", "/");
      edges.push([from, target]);

      // Frontends may depend on core; core must not depend on TUI.
      if (!from.startsWith("tui/") && target.startsWith("tui/")) {
        const key = `${from} -> ${specifier}`;
        if (!ALLOWLIST.has(key)) violations.push(`forbidden core → tui import: ${key}`);
      }
      // The web fetch implementation consumes shared tool contracts directly,
      // not the registry facade, preventing a type-only cycle.
      if (from === "webfetch.ts" && target === "tools.ts") {
        violations.push("webfetch.ts must import contracts from tools/types.ts, not tools.ts");
      }
    }
  }
  if (violations.length > 0) {
    console.error(violations.map((v) => `✗ ${v}`).join("\n"));
    process.exitCode = 1;
  }
  return edges;
}

const edges = check();
if (process.argv.includes("--graph")) {
  const lines = [
    "# Architecture dependency graph",
    "",
    "> Generated by `node scripts/check-layers.mjs --graph`; do not edit manually.",
    "",
    "```mermaid",
    "flowchart LR",
  ];
  const nodes = new Map();
  const id = (name) => {
    if (!nodes.has(name)) nodes.set(name, `n${nodes.size}`);
    return nodes.get(name);
  };
  for (const [from, to] of edges) lines.push(`  ${id(from)}[${from}] --> ${id(to)}[${to}]`);
  lines.push("```");
  mkdirSync(resolve(new URL("..", import.meta.url).pathname, "docs"), { recursive: true });
  writeFileSync(GRAPH_OUT, `${lines.join("\n")}\n`);
  console.log(`✓ wrote ${relative(process.cwd(), GRAPH_OUT)}`);
}

if (process.exitCode !== 1) console.log(`✓ layer check passed (${edges.length} local imports)`);
